import type { CSSProperties, ReactNode } from 'react'
import type { QrAppearance } from '../appearance'
import type { QrContent } from '../content'
import { useQrSvg } from './useQrSvg'

export interface QrCodeProps {
  content: QrContent
  appearance?: QrAppearance
  /** Rendered when the content is incomplete or invalid. Default: nothing. */
  fallback?: ReactNode | ((error: string) => ReactNode)
  className?: string
  style?: CSSProperties
}

/**
 * Displays a QR code. Renders the same SVG the server produces, so SSR output
 * matches the client and no layout shift occurs.
 */
export function QrCode({ content, appearance = {}, fallback = null, className, style }: QrCodeProps) {
  const { svg, error } = useQrSvg(content, appearance)

  if (!svg) {
    return <>{typeof fallback === 'function' ? fallback(error ?? '') : fallback}</>
  }

  return (
    <div
      className={['pga-qr-code', className].filter(Boolean).join(' ')}
      style={style}
      // The SVG is generated by renderQrSvg, which escapes every interpolated value.
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  )
}
